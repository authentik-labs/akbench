#!/usr/bin/env bash
# Migrates an existing akbench management cluster (a `main`-era setup:
# Cluster API + the Incus provider + Flux + the operator, installed by hand)
# onto the single-container appliance - without touching a single running
# workload cluster. See docs/appliance-migration.md for the full procedure,
# rollback and the reasoning behind each step.
#
#   hack/migrate-to-appliance.sh --from-context OLD --to-context NEW [--namespace NS]... [--yes]
#   hack/migrate-to-appliance.sh --from-context OLD --cleanup-source [--namespace NS]... [--yes]
#
# Needs kubectl, clusterctl (>= the source's Cluster API version) and jq.
set -euo pipefail

FROM_KUBECONFIG="${KUBECONFIG:-$HOME/.kube/config}"
TO_KUBECONFIG="${KUBECONFIG:-$HOME/.kube/config}"
FROM_CONTEXT=""
TO_CONTEXT=""
NAMESPACES=()
ASSUME_YES=false
SKIP_NETCHECK=false
CLEANUP_SOURCE=false

BENCH_GROUP="bench.goauthentik.io"
# Everything but WorkloadClusters, in owner-before-dependent order -
# WorkloadClusters (and the whole CAPI tree under them) go through
# `clusterctl move` instead.
COPIED_KINDS=(testcasetemplates authentikdeployments testcases testruns)
ALL_KINDS=(workloadclusters "${COPIED_KINDS[@]}")
TARGET_OPERATOR_NS="authentik-bench"
# The appliance's provider contract with the web UI (internal/appliance/providers.go).
APPLIANCE_NS="authentik-bench"
APPLIANCE_PROVIDERS="appliance-providers"
APPLIANCE_STATUS="appliance-status"
TARGET_OPERATOR_DEPLOY="authentik-bench-operator-controller-manager"

usage() {
    sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'
    exit "${1:-0}"
}

while [[ $# -gt 0 ]]; do
    case "$1" in
    --from-kubeconfig) FROM_KUBECONFIG="$2"; shift 2 ;;
    --from-context) FROM_CONTEXT="$2"; shift 2 ;;
    --to-kubeconfig) TO_KUBECONFIG="$2"; shift 2 ;;
    --to-context) TO_CONTEXT="$2"; shift 2 ;;
    --namespace | -n) NAMESPACES+=("$2"); shift 2 ;;
    --yes | -y) ASSUME_YES=true; shift ;;
    --skip-netcheck) SKIP_NETCHECK=true; shift ;;
    --cleanup-source) CLEANUP_SOURCE=true; shift ;;
    -h | --help) usage ;;
    *) echo "unknown argument: $1" >&2; usage 1 ;;
    esac
done

src() { kubectl --kubeconfig "$FROM_KUBECONFIG" ${FROM_CONTEXT:+--context "$FROM_CONTEXT"} "$@"; }
dst() { kubectl --kubeconfig "$TO_KUBECONFIG" ${TO_CONTEXT:+--context "$TO_CONTEXT"} "$@"; }
step() { printf '\n==> %s\n' "$*" >&2; }
info() { printf '    %s\n' "$*" >&2; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
confirm() {
    $ASSUME_YES && return 0
    local reply
    read -r -p "$1 [y/N] " reply
    [[ "$reply" == y || "$reply" == Y ]] || die "aborted"
}

# Strips everything server-assigned so an object can be created fresh on the
# target. ownerReferences are kept: akbench objects and the ConfigMaps
# deployments own get theirs rewritten to the target's UIDs first
# (rebuild_owner_refs), and the other copied Secrets/ConfigMaps are unowned to
# begin with (user_objects).
STRIP='del(.metadata.uid, .metadata.resourceVersion, .metadata.creationTimestamp,
    .metadata.generation, .metadata.managedFields, .metadata.selfLink,
    .metadata.annotations["kubectl.kubernetes.io/last-applied-configuration"])'

for tool in kubectl jq; do
    command -v "$tool" >/dev/null || die "$tool is required"
done

# Every deployment on the source that would act on objects mid-migration:
# clusterctl move deletes source objects *before* stripping their finalizers,
# so a running operator would tear down the workload cluster its
# WorkloadCluster names, and a running helm-controller would `helm uninstall`
# every release a moved HelmRelease points at.
source_controllers() {
    {
        src get deploy -A -l control-plane=controller-manager,app.kubernetes.io/name=authentik-bench -o json
        src get deploy -A -l app=authentik-bench-apiserver -o json
        src get deploy -A --field-selector metadata.name=helm-controller -o json
    } | jq -r '.items[] | "\(.metadata.namespace) \(.metadata.name) \(.spec.replicas)"'
}

detect_namespaces() {
    if [[ ${#NAMESPACES[@]} -gt 0 ]]; then
        return
    fi
    local kind ns
    for kind in "${ALL_KINDS[@]}"; do
        for ns in $(src get "$kind.$BENCH_GROUP" -A -o jsonpath='{.items[*].metadata.namespace}' 2>/dev/null); do
            NAMESPACES+=("$ns")
        done
    done
    if [[ ${#NAMESPACES[@]} -gt 0 ]]; then
        # shellcheck disable=SC2207 # namespace names never contain whitespace
        NAMESPACES=($(printf '%s\n' "${NAMESPACES[@]}" | sort -u))
    fi
}

# Unowned Secrets/ConfigMaps a user created by hand (Incus credentials,
# fixtures, external Postgres credentials, extra values, custom k6 scripts).
# Owned ones are regenerated by their controller, moved by clusterctl with
# their owner, or - owned by an AuthentikDeployment - copied once it is
# (deployment_configmaps).
user_objects() {
    local ns="$1"
    src -n "$ns" get secrets,configmaps -o json | jq -c '.items[]
        | select((.metadata.ownerReferences // []) | length == 0)
        | select(.type != "kubernetes.io/service-account-token" and .type != "helm.sh/release.v1")
        | select(.metadata.name != "kube-root-ca.crt")'
}

# ConfigMaps owned only by AuthentikDeployments: the extra values saved
# through the web UI, which the API makes the deployment own so they are
# garbage-collected with it. Nothing regenerates them, and a deployment
# whose extraValuesRef names a missing one never becomes ready, so they are
# copied too - after the deployments, whose new UIDs their ownerReferences
# need.
deployment_configmaps() {
    local ns="$1"
    src -n "$ns" get configmaps -o json | jq -c --arg v "$BENCH_GROUP/" '.items[]
        | select((.metadata.ownerReferences // []) | length > 0)
        | select(all(.metadata.ownerReferences[]; .kind == "AuthentikDeployment" and (.apiVersion | startswith($v))))'
}

# Creates obj (JSON) on the target, or - if it already exists - merges the
# source's spec into it, so a rerun after a partial migration converges.
create_or_update() {
    local obj="$1" kind name ns
    kind="$(jq -r .kind <<<"$obj")"
    name="$(jq -r .metadata.name <<<"$obj")"
    ns="$(jq -r .metadata.namespace <<<"$obj")"
    if dst -n "$ns" get "$kind" "$name" >/dev/null 2>&1; then
        if jq -e 'has("spec")' <<<"$obj" >/dev/null; then
            dst -n "$ns" patch "$kind" "$name" --type=merge -p "$(jq -c '{spec: .spec}' <<<"$obj")" >/dev/null
            info "updated $kind/$name"
        else
            info "kept existing $kind/$name"
        fi
    else
        jq "$STRIP | del(.status)" <<<"$obj" | dst create -f - >/dev/null
        info "created $kind/$name"
    fi
}

# Rewrites ownerReferences to akbench objects against the target's UIDs
# (owners are always copied first - see COPIED_KINDS' order), dropping any
# that point at something not migrated.
rebuild_owner_refs() {
    local obj="$1" ns refs="[]" ref kind name uid
    ns="$(jq -r .metadata.namespace <<<"$obj")"
    while read -r ref; do
        [[ -z "$ref" ]] && continue
        kind="$(jq -r .kind <<<"$ref")"
        name="$(jq -r .name <<<"$ref")"
        uid="$(dst -n "$ns" get "$kind.$BENCH_GROUP" "$name" -o jsonpath='{.metadata.uid}' 2>/dev/null || true)"
        if [[ -n "$uid" ]]; then
            refs="$(jq -c --argjson r "$ref" --arg uid "$uid" '. + [$r | .uid = $uid]' <<<"$refs")"
        fi
    done < <(jq -c --arg g "$BENCH_GROUP/" '(.metadata.ownerReferences // [])[] | select(.apiVersion | startswith($g))' <<<"$obj")
    jq -c --argjson refs "$refs" '.metadata.ownerReferences = $refs' <<<"$obj"
}

if $CLEANUP_SOURCE; then
    detect_namespaces
    [[ ${#NAMESPACES[@]} -gt 0 ]] || die "nothing to clean up"
    step "Checking the source is quiesced"
    while read -r ns name replicas; do
        [[ -z "$ns" ]] && continue
        [[ "$replicas" == 0 ]] || die "$ns/$name still has $replicas replicas - run the migration first"
    done < <(source_controllers)
    step "Will strip finalizers from and delete every akbench object and Flux HelmRelease/HelmRepository in: ${NAMESPACES[*]}"
    info "Workload clusters are untouched: they were moved to the appliance, and nothing on the source is running to act on these deletions."
    confirm "Delete them from the source?"
    for ns in "${NAMESPACES[@]}"; do
        for kind in "${COPIED_KINDS[@]/%/.$BENCH_GROUP}" helmreleases.helm.toolkit.fluxcd.io helmrepositories.source.toolkit.fluxcd.io; do
            for name in $(src -n "$ns" get "$kind" -o jsonpath='{.items[*].metadata.name}' 2>/dev/null); do
                src -n "$ns" patch "$kind" "$name" --type=merge -p '{"metadata":{"finalizers":null}}' >/dev/null
                src -n "$ns" delete "$kind" "$name" --wait=false >/dev/null
                info "deleted $kind/$name"
            done
        done
    done
    step "Source cleaned up. The old management cluster can now be deleted."
    exit 0
fi

command -v clusterctl >/dev/null || die "clusterctl is required"
[[ -n "$FROM_CONTEXT$TO_CONTEXT" || "$FROM_KUBECONFIG" != "$TO_KUBECONFIG" ]] ||
    die "pass --from-context/--to-context (or --from-kubeconfig/--to-kubeconfig)"

move_args=(--kubeconfig "$FROM_KUBECONFIG" --to-kubeconfig "$TO_KUBECONFIG")
[[ -n "$FROM_CONTEXT" ]] && move_args+=(--kubeconfig-context "$FROM_CONTEXT")
[[ -n "$TO_CONTEXT" ]] && move_args+=(--to-kubeconfig-context "$TO_CONTEXT")

# --- Preflight ---------------------------------------------------------------
step "Preflight"
src version >/dev/null || die "source cluster unreachable"
dst version >/dev/null || die "target cluster unreachable"
[[ "$(dst get crd "workloadclusters.$BENCH_GROUP" -o jsonpath='{.metadata.labels.clusterctl\.cluster\.x-k8s\.io/move-hierarchy}' 2>/dev/null)" == true ]] ||
    die "target's WorkloadCluster CRD lacks the clusterctl move-hierarchy label - is it an appliance with an akbench version that supports migration, and has it finished bootstrapping?"
dst -n "$TARGET_OPERATOR_NS" get deploy "$TARGET_OPERATOR_DEPLOY" >/dev/null ||
    die "target has no $TARGET_OPERATOR_NS/$TARGET_OPERATOR_DEPLOY - wait for the appliance to finish bootstrapping"

# Infrastructure providers: clusterctl move needs every one the source has
# on the target too. Inside the appliance, missing ones are enabled the same
# way the web UI's Infrastructure page does it (ProvidersConfigMap, see
# internal/appliance/providers.go) once the plan is confirmed.
infra_names() { jq -r '[.items[] | select(.type == "InfrastructureProvider") | .providerName] | unique | .[]'; }
src_infra="$(src get providers.clusterctl.cluster.x-k8s.io -A -o json | infra_names)"
dst_infra="$(dst get providers.clusterctl.cluster.x-k8s.io -A -o json 2>/dev/null | infra_names || true)"
missing_infra=()
for p in $src_infra; do
    grep -qx "$p" <<<"$dst_infra" || missing_infra+=("$p")
done
if [[ ${#missing_infra[@]} -gt 0 ]] && ! dst -n "$APPLIANCE_NS" get configmap "$APPLIANCE_STATUS" >/dev/null 2>&1; then
    die "the target lacks the infrastructure provider(s) ${missing_infra[*]} - install them with clusterctl init --infrastructure first"
fi

detect_namespaces
[[ ${#NAMESPACES[@]} -gt 0 ]] || die "no akbench objects found on the source"
info "namespaces: ${NAMESPACES[*]}"

controllers="$(source_controllers)"
[[ -n "$controllers" ]] || info "no operator/apiserver/helm-controller Deployments found on the source"

local_deployments=""
local_targets=""
for ns in "${NAMESPACES[@]}"; do
    local_deployments+="$(src -n "$ns" get "authentikdeployments.$BENCH_GROUP" -o json |
        jq -r '.items[] | select((.spec.clusterRef.name // "") == "") | "    AuthentikDeployment \(.metadata.namespace)/\(.metadata.name)\n"')"
    local_targets+="$(src -n "$ns" get "testcases.$BENCH_GROUP" -o json |
        jq -r '.items[] | select((.spec.runnerClusterRef.name // "") == "") | "    TestCase \(.metadata.namespace)/\(.metadata.name)\n"')"
done
# The appliance rejects AuthentikDeployments without a clusterRef.
[[ -z "$local_deployments" ]] ||
    die "$(printf 'these AuthentikDeployments run on the old management cluster itself, which the appliance does not allow - delete them or recreate them on a workload cluster first:\n%b' "$local_deployments")"

if ! $SKIP_NETCHECK; then
    # The appliance must reach each workload cluster's API through its load
    # balancer - outbound only, the same requirement the old management
    # cluster had. Checked from inside the target, where the operator runs.
    for ns in "${NAMESPACES[@]}"; do
        while read -r cluster endpoint; do
            [[ -z "$cluster" ]] && continue
            info "checking the appliance can reach $cluster at $endpoint"
            dst -n "$TARGET_OPERATOR_NS" run "akbench-netcheck-$RANDOM" --rm -i --quiet --restart=Never \
                --image=curlimages/curl:8.17.0 -- curl -sk -o /dev/null --connect-timeout 5 "https://$endpoint/" ||
                die "the appliance can't reach $cluster's API at $endpoint - fix routing to the infrastructure's network first (or --skip-netcheck)"
        done < <(src -n "$ns" get clusters.cluster.x-k8s.io -o json |
            jq -r '.items[] | select(.spec.controlPlaneEndpoint.host // "" != "") | "\(.metadata.name) \(.spec.controlPlaneEndpoint.host):\(.spec.controlPlaneEndpoint.port)"')
    done
fi

# clusterctl move's own dry run: catches older target providers and an
# unmovable object graph before anything has been changed. The source CRD
# label is what makes WorkloadClusters part of that graph (see the marker on
# api/v1alpha1/workloadcluster_types.go); adding it changes nothing else.
# Only possible once the target has every provider - otherwise it runs
# after they're installed below.
dry_run() {
    src label crd "workloadclusters.$BENCH_GROUP" clusterctl.cluster.x-k8s.io/move-hierarchy=true --overwrite >/dev/null
    local ns out
    for ns in "${NAMESPACES[@]}"; do
        info "clusterctl move --dry-run -n $ns"
        # Quiet unless it fails: a dry run still logs "Deleting objects from
        # the source cluster", which is alarming to read before anything was
        # agreed to.
        if ! out="$(clusterctl move "${move_args[@]}" -n "$ns" --dry-run 2>&1)"; then
            printf '%s\n' "$out" >&2
            die "clusterctl move --dry-run failed for namespace $ns"
        fi
    done
}
if [[ ${#missing_infra[@]} -eq 0 ]]; then
    dry_run
fi

# --- Plan ----------------------------------------------------------------------
step "Plan"
if [[ ${#missing_infra[@]} -gt 0 ]]; then
    info "0. Install the infrastructure provider(s) ${missing_infra[*]} on the appliance."
fi
cat >&2 <<EOF
    1. Scale to 0 on the source (also stop any 'make dev'/'make run' operator you run locally):
$(sed 's/^/         /' <<<"${controllers:-(none)}")
    2. Hold the appliance's operator (suspend its HelmRelease, scale to 0).
    3. Copy hand-made Secrets/ConfigMaps from ${NAMESPACES[*]} (existing ones on the appliance are kept).
    4. clusterctl move every WorkloadCluster with its Cluster API tree and HelmReleases.
    5. Copy ${COPIED_KINDS[*]} with their status, then the ConfigMaps deployments own (extra values).
    6. Resume the appliance's operator and wait for every WorkloadCluster to become Ready.
EOF
if [[ -n "$local_targets" ]]; then
    printf '\n    These run on the old management cluster itself and will be installed fresh on\n    the appliance (no data is carried over - e.g. an embedded Postgres starts empty):\n%b' "$local_targets" >&2
fi
confirm "Proceed?"

# --- 0. Infrastructure providers ---------------------------------------------
if [[ ${#missing_infra[@]} -gt 0 ]]; then
    step "Installing infrastructure providers on the appliance: ${missing_infra[*]}"
    enabled="$(dst -n "$APPLIANCE_NS" get configmap "$APPLIANCE_PROVIDERS" --ignore-not-found \
        -o jsonpath='{.data.infrastructure}')"
    for p in "${missing_infra[@]}"; do
        grep -qx "$p" <<<"${enabled//,/$'\n'}" || enabled="${enabled:+$enabled,}$p"
    done
    dst -n "$APPLIANCE_NS" create configmap "$APPLIANCE_PROVIDERS" --from-literal=infrastructure="$enabled" \
        --dry-run=client -o yaml | dst apply -f - >/dev/null
    for _ in $(seq 1 120); do
        dst_infra="$(dst get providers.clusterctl.cluster.x-k8s.io -A -o json 2>/dev/null | infra_names || true)"
        still_missing=()
        for p in "${missing_infra[@]}"; do
            grep -qx "$p" <<<"$dst_infra" || still_missing+=("$p")
        done
        [[ ${#still_missing[@]} -eq 0 ]] && break
        sleep 5
    done
    if [[ ${#still_missing[@]} -gt 0 ]]; then
        err="$(dst -n "$APPLIANCE_NS" get configmap "$APPLIANCE_STATUS" -o jsonpath='{.data.error}' 2>/dev/null || true)"
        die "the appliance didn't install ${still_missing[*]} within 10 minutes${err:+: $err}"
    fi
    dry_run
fi

# --- 1. Quiesce the source ---------------------------------------------------
step "Quiescing the source"
while read -r ns name replicas; do
    [[ -z "$ns" ]] && continue
    src -n "$ns" scale deploy "$name" --replicas=0 >/dev/null
    info "scaled $ns/$name to 0 (was $replicas; to roll back: kubectl -n $ns scale deploy $name --replicas=$replicas)"
done <<<"$controllers"
while read -r ns name _; do
    [[ -z "$ns" ]] && continue
    src -n "$ns" rollout status deploy "$name" --timeout=120s >/dev/null
done <<<"$controllers"

# --- 2. Hold the target's operator ----------------------------------------------
step "Holding the appliance's operator"
dst -n flux-system patch helmrelease authentik-bench-operator --type=merge -p '{"spec":{"suspend":true}}' >/dev/null
dst -n "$TARGET_OPERATOR_NS" scale deploy "$TARGET_OPERATOR_DEPLOY" --replicas=0 >/dev/null
dst -n "$TARGET_OPERATOR_NS" rollout status deploy "$TARGET_OPERATOR_DEPLOY" --timeout=120s >/dev/null

# --- 3. Hand-made Secrets/ConfigMaps --------------------------------------------
step "Copying Secrets/ConfigMaps"
for ns in "${NAMESPACES[@]}"; do
    dst get ns "$ns" >/dev/null 2>&1 || dst create ns "$ns" >/dev/null
    while read -r obj; do
        [[ -z "$obj" ]] && continue
        kind="$(jq -r .kind <<<"$obj")"
        name="$(jq -r .metadata.name <<<"$obj")"
        if dst -n "$ns" get "$kind" "$name" >/dev/null 2>&1; then
            info "kept existing $kind/$name"
        else
            jq "$STRIP" <<<"$obj" | dst create -f - >/dev/null
            info "created $kind/$name"
        fi
    done < <(user_objects "$ns")
done

# --- 4. clusterctl move -------------------------------------------------------------
for ns in "${NAMESPACES[@]}"; do
    step "clusterctl move -n $ns"
    clusterctl move "${move_args[@]}" -n "$ns"
done

# --- 5. akbench objects ------------------------------------------------------------
step "Copying akbench objects"
for kind in "${COPIED_KINDS[@]}"; do
    for ns in "${NAMESPACES[@]}"; do
        while read -r obj; do
            [[ -z "$obj" ]] && continue
            name="$(jq -r .metadata.name <<<"$obj")"
            if jq -e '.metadata.deletionTimestamp' <<<"$obj" >/dev/null; then
                info "skipped $kind/$name: being deleted on the source"
                continue
            fi
            create_or_update "$(rebuild_owner_refs "$obj")"
            # Status is not part of a create; restored separately so e.g. a
            # finished TestRun stays finished (and isn't re-run) and keeps the
            # start/completion times the Compare view keys on.
            if jq -e '.status' <<<"$obj" >/dev/null; then
                dst -n "$ns" patch "$kind.$BENCH_GROUP" "$name" --subresource=status --type=merge \
                    -p "$(jq -c '{status: .status}' <<<"$obj")" >/dev/null
            fi
        done < <(src -n "$ns" get "$kind.$BENCH_GROUP" -o json | jq -c '.items[]')
    done
done

# The operator is still held, so a deployment copied above doesn't see its
# extra-values ConfigMap missing before this creates it.
step "Copying ConfigMaps owned by AuthentikDeployments"
for ns in "${NAMESPACES[@]}"; do
    while read -r obj; do
        [[ -z "$obj" ]] && continue
        name="$(jq -r .metadata.name <<<"$obj")"
        obj="$(rebuild_owner_refs "$obj")"
        # Its deployment was not copied (e.g. being deleted on the source),
        # so neither is it: unowned on the target, it would never be cleaned up.
        if jq -e '.metadata.ownerReferences | length == 0' <<<"$obj" >/dev/null; then
            info "skipped ConfigMap/$name: its AuthentikDeployment was not copied"
            continue
        fi
        create_or_update "$obj"
    done < <(deployment_configmaps "$ns")
done

# --- 6. Resume -------------------------------------------------------------------
step "Resuming the appliance's operator"
dst -n flux-system patch helmrelease authentik-bench-operator --type=merge -p '{"spec":{"suspend":false}}' >/dev/null
dst -n "$TARGET_OPERATOR_NS" scale deploy "$TARGET_OPERATOR_DEPLOY" --replicas=1 >/dev/null
dst -n "$TARGET_OPERATOR_NS" rollout status deploy "$TARGET_OPERATOR_DEPLOY" --timeout=300s >/dev/null

step "Waiting for WorkloadClusters to become Ready"
for ns in "${NAMESPACES[@]}"; do
    if [[ -n "$(dst -n "$ns" get "workloadclusters.$BENCH_GROUP" -o name)" ]]; then
        dst -n "$ns" wait "workloadclusters.$BENCH_GROUP" --all --for=condition=Ready --timeout=15m ||
            info "not all WorkloadClusters in $ns are Ready yet - check: kubectl -n $ns get workloadclusters,helmreleases"
    fi
done

step "Migration complete"
cat >&2 <<EOF
    The source management cluster is quiesced. Do NOT scale its operator or
    helm-controller back up: they would fight the appliance over the same
    workload clusters. Once you're happy with the appliance, either delete the
    old cluster outright, or first remove the leftover objects safely with:

      $0 ${FROM_CONTEXT:+--from-context $FROM_CONTEXT }--cleanup-source $(printf -- '-n %s ' "${NAMESPACES[@]}")
EOF
